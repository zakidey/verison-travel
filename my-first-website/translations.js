// قراءة اللغة الحالية
function getCurrentLang() {
    return localStorage.getItem("selectedLang") || "ar";
}

// دالة تغيير اللغة وتطبيق الاتجاه والنصوص
function setLanguage(lang) {
    if (!translations[lang]) lang = 'ar';
    
    localStorage.setItem("selectedLang", lang);

    // تغيير الاتجاه (RTL للعربية / LTR للفرنسية والإنجليزية)
    if (lang === "ar") {
        document.documentElement.dir = "rtl";
        document.documentElement.lang = "ar";
    } else {
        document.documentElement.dir = "ltr";
        document.documentElement.lang = lang;
    }

    // ترجمة النصوص العامة
    document.querySelectorAll("[data-key], [data-i18n]").forEach(el => {
        const key = el.getAttribute("data-key") || el.getAttribute("data-i18n");
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // ترجمة خانات الإدخال Placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (translations[lang] && translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    // تحديث زر اللغة
    const langBtn = document.getElementById("langBtn");
    if (langBtn) {
        langBtn.textContent = lang.toUpperCase();
    }
}

// دالة التحويل زر واحد (AR -> FR -> EN -> AR)
function toggleLanguage() {
    const currentLang = getCurrentLang();
    let nextLang = 'ar';

    if (currentLang === 'ar') nextLang = 'fr';
    else if (currentLang === 'fr') nextLang = 'en';
    else nextLang = 'ar';

    setLanguage(nextLang);
}

// تشغيل اللغة عند التحميل
document.addEventListener("DOMContentLoaded", () => {
    const savedLang = getCurrentLang();
    setLanguage(savedLang);
});
